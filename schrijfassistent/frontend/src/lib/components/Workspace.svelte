    /**
     * Escape: the draft is dropped. The input unmounts and its blur still calls `saveTitle`, which then finds the
     * current title and saves nothing; the manual-title claim of the keystrokes is undone, so the automatic title
     * suggestion stays available for a nota that never had a title of its own.
     */
    function cancelTitleEdit() {
        titleDraft = nota?.title ?? '';
        if (!titleEditWasManuallySet && nota?.titleManuallySet) setTitleManuallySet(false);
        titleEditing = false;
    }

    /** Saves title to db and exits edit mode. */
    function saveTitle() {
        // the input stops at the limit; a value that got in another way (paste into a field without the attribute) is cut here
        const trimmed = titleDraft.trim().slice(0, MAX_NOTA_TITLE_LENGTH).trim();
        if (!trimmed || trimmed === nota.title) { titleEditing = false; return; }
        markTitleManuallySet();
        const db = get(dbStore);
        const notaIndex = db.notas.findIndex(n => n.id === notaId);
        if (notaIndex > -1) {
            db.notas[notaIndex].title = trimmed;
            db.notas[notaIndex].titleManuallySet = true;
            db.notas[notaIndex].lastModified = new Date().toISOString();
            saveDB();
            triggerAutosaveDebounce(); // Start autosave timer after title edit
            nota = { ...nota, title: trimmed, titleManuallySet: true };
        }
        titleEditing = false;
    }

    /** WIP / Final-draft / Final at nota level. */
    function handleStatusChange(newStatus) {
        const db = get(dbStore);
        const notaIndex = db.notas.findIndex(n => n.id === notaId);
        if (notaIndex > -1) {
            db.notas[notaIndex].status = newStatus;
            db.notas[notaIndex].lastModified = new Date().toISOString();
            saveDB();
            triggerAutosaveDebounce(); // Start autosave timer after status change
            nota = { ...nota, status: newStatus };
        }
    }

    /**
     * Esc in full-screen writing mode ("Druk Esc om te sluiten" in the block's footer) collapses the block, wherever
     * the focus is. A dialog that is open inside the app (the suggestion modal, a confirmation) takes that Esc first:
     * its own listener closes it, and the block collapses on the next Esc. The listener runs in the capture phase so
     * that it sees the dialog before the modal's bubble listener removes it (Svelte flushes that removal synchronously).
     * Plain Esc keeps bubbling to the host, as before (main.js stopHostShortcuts); a chord with a modifier is not ours.
     * @param {KeyboardEvent} e
     */
    function handleWindowKeydown(e) {
        if (e.key !== 'Escape' || e.ctrlKey || e.metaKey || e.altKey || e.shiftKey) return;
        if (!expandedBlockId) return;
        if (root().querySelector('[role="dialog"]')) return;
        expandedBlockId = null;
    }

    /**
     * Copies the plain text of the whole nota to the clipboard (utils/clipboardText.js): one line per chapter title,
     * paragraphs on their own lines, entities decoded, and the untouched instructions of the template left out.
     */
    function copyAll() {
        const db = get(dbStore);
        const config = (db.configurations || []).find((c) => c.id === (nota?.configId || 'conf-gs')) || db.configurations?.[0];
        const placeholders = (config?.templateGuidelines || []).map((g) => g?.instructie || '');
        const text = notaBlocksToClipboardText(parseContentToBlocks(content), { placeholders });
        navigator.clipboard.writeText(text);
        // Information goes to a toast, not to a native dialog.
        addNotification('Volledige nota gekopieerd naar klembord', 'success');
    }

    /** Reviewer: opens selection bubble on text selection in a cell. */
    function handleMouseUp(e) {
        if (!nota || currentUser.role !== 'reviewer') return;
        if (e.target.closest('.selection-bubble')) return;

        const sel = window.getSelection();
        if (!sel || sel.isCollapsed || sel.rangeCount === 0) return;

        const range = sel.getRangeAt(0);
        const cellContent = range.commonAncestorContainer.nodeType === 1
            ? range.commonAncestorContainer.closest('.cell-content')
            : range.commonAncestorContainer.parentElement?.closest('.cell-content');

        if (!cellContent) return;

        const rect = range.getBoundingClientRect();
        selectionBubble = {
            x: rect.left + rect.width / 2,
            y: rect.top - 8,
            savedRange: range.cloneRange(),
            step: 'type',
            noteType: null
        };
    }

    /** Closes reviewer selection bubble and clears selection. */
    function dismissBubble() {
        selectionBubble = null;
        window.getSelection()?.removeAllRanges();
    }

    /**
     * Opens suggestion modal for an inline highlight (workspace / editor).
     * @param {string} suggestionId
     * @param {string} [blockId]
     */
    function triggerMockSuggestion(suggestionId, blockId) {
        const bid = blockId || activeBlockId;
        if (!bid || !lastSuggestions[bid]) return;
        if (isBlockWorkflowDone(bid)) return;

        const suggestionIndex = lastSuggestions[bid].findIndex(s => s.id === suggestionId);
        if (suggestionIndex === -1) return;

        const realSuggestion = lastSuggestions[bid][suggestionIndex];

        showSuggestionModal({
            originalText: realSuggestion.original,
            suggestedText: realSuggestion.suggested,
            explanation: realSuggestion.explanation || '',
            alternatives: realSuggestion.alternatives,
            b1AlternativesIncomplete: realSuggestion.b1AlternativesIncomplete === true,
            ruleDetails: realSuggestion.ruleDetails || [],
            referenceLinks: realSuggestion.referenceLinks || [],
            handbookSnippet: realSuggestion.handbookSnippet || '',
            canAccept: realSuggestion.canAccept !== false,
            highlightId: suggestionId,
            /** Lets the global modal resolve “next” and keyboard navigation in the workspace queue. */
            blockId: bid,
            source: realSuggestion.source,
            onAccept: (newText) => {
                if (realSuggestion.canAccept === false) return;
                if (isBlockWorkflowDone(bid)) return;
                dismissedSuggestionIds = new Set(dismissedSuggestionIds).add(suggestionId);

                const isStructuurAccept = suggestionId.startsWith('agent_structuur-');
                if (editorInstances[bid] && newText != null) {
                    // For structuur: replace entire content (no text matching needed)
                    if (isStructuurAccept) {
                        skipNextAutoAi = true;
                        editorInstances[bid].setContent(newText);
                    } else {
                        // For B1/spelling: precise text replacement
                        editorInstances[bid].replaceText(realSuggestion.original, newText);
                    }
                }

                acceptedSuggestions = {
                    ...acceptedSuggestions,
                    [suggestionId]: {
                        originalText: realSuggestion.original,
                        appliedText: newText,
                        blockId: bid
                    }
                };

                // Structuur accept: woordenlijst suggestions go stale; B1/spelling are cleared + re-run below.
                if (isStructuurAccept) {
                    const blockSuggestions = lastSuggestions[bid] || [];
                    const toDismiss = blockSuggestions
                        .filter((s) => s.id.startsWith('agent_woordenlijst-'))
                        .map((s) => s.id);
                    if (toDismiss.length > 0) {
                        const updated = new Set(dismissedSuggestionIds);
                        toDismiss.forEach((id) => updated.add(id));
                        dismissedSuggestionIds = updated;
                    }
                    regenerateSpellingAndB1AfterStructuurAccept(bid).catch((e) =>
                        console.error('Spelling/B1 refresh after structuur accept failed', e)
                    );
                }

                syncLastSuggestionsFromNota();
                scheduleAutoAdvanceAfterClose(bid, suggestionId);
            },
            onDeny: () => {
                dismissedSuggestionIds = new Set(dismissedSuggestionIds).add(suggestionId);
                syncLastSuggestionsFromNota();
                scheduleAutoAdvanceAfterClose(bid, suggestionId);
            }
        });
    }

    /**
     * Reverses a specific accepted suggestion by calling replaceText in reverse.
     * Subsequent manual edits to the block survive because only the stored `appliedText`
     * is searched for and replaced — not a full block snapshot.
     * When the applied text can no longer be found (author edited it away), the suggestion
     * is still removed from acceptedSuggestions and added back to pending so the sidebar
     * reflects the correct state; a console.warn is emitted for diagnostics.
     * @param {string} suggestionId
     */
    function undoAcceptedSuggestion(suggestionId) {
        const entry = acceptedSuggestions[suggestionId];
        if (!entry) return;
        if (isBlockWorkflowDone(entry.blockId)) return;
        let replaced = false;
        if (editorInstances[entry.blockId]) {
            replaced = editorInstances[entry.blockId].replaceText(entry.appliedText, entry.originalText);
        }
        if (!replaced) {
            console.warn(`Undo not possible: appliedText not found in block ${entry.blockId}`);
        }
        const next = { ...acceptedSuggestions };
        delete next[suggestionId];
        acceptedSuggestions = next;
        dismissedSuggestionIds = new Set(
            [...dismissedSuggestionIds].filter((id) => id !== suggestionId)
        );
        syncLastSuggestionsFromNota();
    }

    /**
     * Reviewer: wraps selection in highlight span and appends note to nota.
     * @param {{ text: string, type: string }} detail
     */
    function handleSubmitNote(detail) {
        const { text, type } = detail;
        const noteId = 'note-' + Date.now();
        const revColor = getReviewerColor(currentUser.name);
        let updatedContent = content;

        const sel = window.getSelection();
        try {
            sel.removeAllRanges();
            sel.addRange(selectionBubble.savedRange);
            const range = sel.getRangeAt(0);

            const cellContent = range.commonAncestorContainer.nodeType === 1
                ? range.commonAncestorContainer.closest('.cell-content')
                : range.commonAncestorContainer.parentElement?.closest('.cell-content');

            if (cellContent) {
                const span = document.createElement('span');
                span.className = 'reviewer-highlight';
                span.setAttribute('data-note-id', noteId);
                span.style.backgroundColor = revColor + '30';
                span.style.borderBottom = `2px solid ${revColor}`;
                span.title = `Notitie van ${currentUser.name} (${type}): ${text.substring(0, 30)}...`;
                range.surroundContents(span);

                const blocksContainer = root().querySelector('.editor-blocks-container');
                if (blocksContainer) {
                    let reconstructedHtml = '';
                    blocksContainer.querySelectorAll('.editor-cell').forEach(cell => {
                        const header = cell.querySelector('h2.dynamic-chapter');
                        const body = cell.querySelector('.cell-content');
                        if (header) reconstructedHtml += header.outerHTML + '\n';
                        if (body) reconstructedHtml += body.innerHTML + '\n';
                    });
                    updatedContent = reconstructedHtml;
                }
                sel.removeAllRanges();
            }
        } catch (e) {
            console.error('Could not wrap selection:', e);
        }

        const noteObj = {
            id: noteId,
            reviewerName: currentUser.name,
            text,
            type,
            timestamp: new Date().toISOString(),
            resolved: false
        };

        const db = get(dbStore);
        const nIndex = db.notas.findIndex(n => n.id === notaId);
        if (nIndex > -1) {
            db.notas[nIndex].notes = [noteObj, ...(db.notas[nIndex].notes || [])];
            if (!db.notas[nIndex].reviewers.includes(currentUser.name)) {
                db.notas[nIndex].reviewers.push(currentUser.name);
            }
            db.notas[nIndex].content = updatedContent;
            db.notas[nIndex].lastModified = new Date().toISOString();
            saveDB();
            triggerAutosaveDebounce(); // Start autosave timer after note creation
            nota = { ...db.notas[nIndex] };
            content = updatedContent;
            dbStore.set(db);
        }
        dismissBubble();
    }


    /** Removes note and matching span from HTML. */
    function removeNote(noteId) {
        // Reviewer notes are unreachable (no Open WebUI user is granted the reviewer role), so this native confirm is never shown;
        // replace it with the typed-confirmation modal when a reviewer mechanism exists.
        if (!window.confirm('Weet u zeker dat u deze notitie wilt verwijderen?')) return;
        const db = get(dbStore);
        const nIndex = db.notas.findIndex(n => n.id === notaId);
        if (nIndex > -1) {
            db.notas[nIndex].notes = db.notas[nIndex].notes.filter(n => n.id !== noteId);
            const tempDiv = document.createElement('div');
            setNotaHtml(tempDiv, db.notas[nIndex].content); // SAFETY
            const span = tempDiv.querySelector(`span[data-note-id="${noteId}"]`);
            if (span) {
                span.replaceWith(document.createTextNode(span.textContent));
                db.notas[nIndex].content = tempDiv.innerHTML;
            }
            saveDB();
            nota = { ...db.notas[nIndex] };
            content = db.notas[nIndex].content;
            dbStore.set(db);
            if (activeNote === noteId) activeNote = null;
        }
    }

    /** Toggles note resolved state and syncs CSS class on span. */
    function toggleNoteResolved(noteId) {
        const db = get(dbStore);
        const nIndex = db.notas.findIndex(n => n.id === notaId);
        if (nIndex > -1) {
            const note = db.notas[nIndex].notes.find(n => n.id === noteId);
            if (note) {
                note.resolved = !note.resolved;
                const tempDiv = document.createElement('div');
                setNotaHtml(tempDiv, db.notas[nIndex].content); // SAFETY
                const span = tempDiv.querySelector(`span[data-note-id="${noteId}"]`);
                if (span) {
                    if (note.resolved) span.classList.add('resolved');
                    else span.classList.remove('resolved');
                    db.notas[nIndex].content = tempDiv.innerHTML;
                }
                saveDB();
                nota = { ...db.notas[nIndex] };
                content = db.notas[nIndex].content;
                dbStore.set(db);
            }
        }
    }
