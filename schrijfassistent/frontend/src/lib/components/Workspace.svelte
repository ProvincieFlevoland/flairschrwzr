    /** Taalreview via `generate-agent-response` + `agent_spelling_grammatica` (zelfde pad als structuur/B1). */
    async function triggerSpellingCheck(blockId, chapterId) {
        const wfLive = getBlockWorkflowMapLive();
        if (!isWorkflowAiEnabled(wfLive, blockId)) return;

        const blocks = parseContentToBlocks(content ?? '');
        const block = blocks.find((b) => b.id === blockId && b.chapterId === chapterId);
        if (!block) {
