            const curT = cur.lastModified ? Date.parse(cur.lastModified) : 0;
            const remT = remote.lastModified ? Date.parse(remote.lastModified) : 0;
            if (remT <= curT) return;
            const nextNota = {
                ...cur,
                blockWorkflow: remote.blockWorkflow ?? cur.blockWorkflow,
                status: remote.status ?? cur.status,
                notes: Array.isArray(remote.notes) ? remote.notes : cur.notes,
                lastModified: remote.lastModified
            };
            const nextNotas = [...db.notas];
            nextNotas[idx] = nextNota;
            dbStore.set({ ...db, notas: nextNotas });
            saveDB();
        } catch (e) {
            console.warn('[Workspace] mergeRemoteNotaSafeFields failed', e);
        }
