    /**
     * Calls backend `generate-agent-response`; writes feedback to structuur, B1, or taalreview field.
     * @param {string} blockId
     * @param {string} chapterId
     * @param {string} blockContent
     * @param {'agent_structuur'|'agent_b1'|'agent_spelling_grammatica'|'agent_woordenlijst'} [assignment]
     */
    async function triggerAiAnalysis(blockId, chapterId, blockContent, assignment = 'agent_structuur') {
        if (!isCurrentGeneration(componentGeneration)) return;
        const analysisKey = `${blockId}-${assignment}`;
        if (assignmentsAnalyzing.has(analysisKey)) return;
        const wfLive = getBlockWorkflowMapLive();
        if (!isWorkflowAiEnabled(wfLive, blockId)) return;

        // Clear any pending automated timer if this was triggered manually
        if (aiTimers[blockId]) {
            clearTimeout(aiTimers[blockId]);
            delete aiTimers[blockId];
        }
        if (aiAgentPendingUntil[blockId] != null) {
            const next = { ...aiAgentPendingUntil };
            delete next[blockId];
            aiAgentPendingUntil = next;
        }

        console.log(`Triggering AI Analysis (${assignment}):`, { blockId, chapterId, blockContentLength: blockContent?.length });

        assignmentsAnalyzing.add(analysisKey);
        if (!blocksAnalyzing.has(blockId)) {
            blocksAnalyzing.add(blockId);
            blocksAnalyzing = new Set(blocksAnalyzing); // Trigger reactivity
        }

        const gen = getGeneration();
        try {
            const configId = nota.configId || nota.templateVersion;
            console.log("Using configId:", configId);

            // the chapter text travels in the JSON body (the query form removes the 8 KB Front Door URL limit risk and
            // keeps the text out of access logs); only the three ids stay in the query string.
            const params = new URLSearchParams({
                config_id: configId,
                chapter_id: chapterId,
                assignment: assignment
            });
            const userMessage =
                assignment === 'agent_spelling_grammatica'
                    ? stripBlockPlainForTaalreview(blockContent ?? '')
                    : stripBlockPlain(blockContent ?? '');

            const response = await storageFetch(`/generate-agent-response?${params.toString()}`, {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({ user_message: userMessage })
            });

            // A late answer of an earlier session (unmount, remount for another user) is dropped.
            if (!isCurrentGeneration(gen)) return;
            if (response.ok) {
                const data = await response.json();
                if (!isCurrentGeneration(gen)) return;
                console.log("AI Analysis Successful. Keys received:", data && typeof data === 'object' ? Object.keys(data) : typeof data);
                const feedback = boundedAiResponse(data.ai_response);

                const feedbackField = feedbackFieldForAssignment(assignment);
                if (!nota[feedbackField]) nota[feedbackField] = {};
                nota[feedbackField][chapterId] = feedback;

                dbStore.update(db => {
                    const idx = db.notas.findIndex(n => n.id === nota.id);
                    if (idx !== -1) {
                        if (!db.notas[idx][feedbackField]) db.notas[idx][feedbackField] = {};
                        db.notas[idx][feedbackField][chapterId] = feedback;
                    }
                    return { ...db };
                });
                saveDB();

                // Save feedback to nota
                const db = get(dbStore);
                const nIdx = db.notas.findIndex(n => n.id === notaId);
                if (nIdx > -1) {
                    const feedbackKey = feedbackFieldForAssignment(assignment);
                    if (!db.notas[nIdx][feedbackKey]) db.notas[nIdx][feedbackKey] = {};
                    db.notas[nIdx][feedbackKey][chapterId] = feedback;
                    console.log(`Updating ${feedbackKey} for`, chapterId);
                    clearDismissedMatchingPrefix(dismissPrefixForAssignment(assignment, chapterId, blockId));
                    dbStore.set({ ...db });
                    saveDB();
                    nota = { ...db.notas[nIdx] };
                }
            } else {
                const errorText = await response.text();
                if (!isCurrentGeneration(gen)) return;
                // The body of a failed call can quote the nota (the AI's raw answer): the console gets the status only.
                console.error("AI analysis failed: HTTP", response.status);

                let errorMessage = "Fout bij de AI analyse.";
                let rawResponse = null;
                try {
                    const errorJson = JSON.parse(errorText);
                    if (errorJson.detail && typeof errorJson.detail === 'object') {
                        errorMessage = errorJson.detail.details || errorJson.detail.error || errorMessage;
                        // `raw_response` (the AI's raw answer, which quotes the nota) is not stored with the nota any more.
                    } else if (typeof errorJson.detail === 'string') {
                        errorMessage = errorJson.detail;
                    }
                } catch (e) {
                    errorMessage = errorText;
                }
                errorMessage = boundedErrorText(errorMessage);

                // Show error in UI instead of just console
                const db = get(dbStore);
                const nIdx = db.notas.findIndex(n => n.id === notaId);
                if (nIdx > -1) {
                    const feedbackKey = feedbackFieldForAssignment(assignment);
                    if (!db.notas[nIdx][feedbackKey]) db.notas[nIdx][feedbackKey] = {};
                    db.notas[nIdx][feedbackKey][chapterId] = {
                        "FOUT": errorMessage,
                        "RAW": rawResponse
                    };
                    dbStore.set({ ...db });
                    saveDB();
                    nota = { ...db.notas[nIdx] };
                }
            }
        } catch (err) {
            if (!isCurrentGeneration(gen)) return;
            console.error("Error triggering AI analysis:", err && err.name);
            // Show generic error in UI
            const db = get(dbStore);
            const nIdx = db.notas.findIndex(n => n.id === notaId);
            if (nIdx > -1) {
                const feedbackKey = feedbackFieldForAssignment(assignment);
                if (!db.notas[nIdx][feedbackKey]) db.notas[nIdx][feedbackKey] = {};
                db.notas[nIdx][feedbackKey][chapterId] = { "FOUT": describeApiUnreachableError() };
                dbStore.set({ ...db });
                saveDB();
                nota = { ...db.notas[nIdx] };
            }
        } finally {
            assignmentsAnalyzing.delete(analysisKey);

            // Only remove from blocksAnalyzing if no more agents are running for this block
            const stillRunningAgent = Array.from(assignmentsAnalyzing).some(k => k.startsWith(`${blockId}-`));
            if (!stillRunningAgent) {
                blocksAnalyzing.delete(blockId);
                blocksAnalyzing = new Set(blocksAnalyzing);
            }
        }
    }

