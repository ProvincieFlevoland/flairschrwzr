<script context="module">
    /**
     * The auto-AI countdowns and the auto-title timer of every Workspace instance that
     * ever mounted, so the close sequence can clear them all. The cleanup in `onMount` below does not run on every
     * path (see the early return there), so a timer of a Workspace that was left through the header still fires
     * after its component is gone; `clearAllWorkspaceTimers()` is the one place that stops them before the host unmounts.
     * An instance stays in the set until the next close, which holds its small timer state for that long.
     * @type {Set<() => void>}
     */
    const timerClearers = new Set();

    /**
     * Set by `clearAllWorkspaceTimers` (close sequence, unmount): while it is true no instance arms a new auto-AI
     * countdown or auto-title timer, so typing during the awaited save of a close (up to the retries) cannot
     * schedule work for a workspace that is about to be destroyed. `mount()` clears it.
     */
    let workspaceDisposed = false;
    export function setWorkspaceDisposed(value) {
        workspaceDisposed = !!value;
    }

    /** Clears the auto-AI countdowns and the auto-title timer of every Workspace instance (called by `App.performClose` and `unmount()`). */
    export function clearAllWorkspaceTimers() {
        workspaceDisposed = true;
        for (const clear of timerClearers) clear();
        timerClearers.clear();
    }
</script>

