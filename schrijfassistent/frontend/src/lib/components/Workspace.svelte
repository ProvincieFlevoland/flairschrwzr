        const db = get(dbStore);
        const liveNota = db.notas.find(n => n.id === notaId) || nota;
        const blocks = parseContentToBlocks(content ?? '');
        const next = {};
        for (const block of blocks) {
            if (!block.chapterId) continue;
            const plain = stripBlockPlain(block.content);
            const list = [];
            list.push(
                ...feedbackToSuggestions(
                    parseAgentFeedback(liveNota.chapterFeedbacks?.[block.chapterId]),
                    block.id,
                    block.chapterId,
                    'agent_structuur',
                    plain
                )
            );
            list.push(
                ...feedbackToSuggestions(
                    parseAgentFeedback(liveNota.chapterFeedbacksB1?.[block.chapterId]),
                    block.id,
                    block.chapterId,
                    'agent_b1',
                    plain
                )
            );
            list.push(
                ...feedbackToSuggestions(
                    parseAgentFeedback(liveNota.chapterFeedbacksWoordenlijst?.[block.chapterId]),
                    block.id,
                    block.chapterId,
                    'agent_woordenlijst',
                    plain
                )
            );
            const spellRaw = liveNota.chapterFeedbacksSpelling?.[block.chapterId];
            const spellObj =
                typeof spellRaw === 'string'
                    ? parseAgentFeedback(spellRaw)
                    : spellRaw && typeof spellRaw === 'object'
                      ? spellRaw
                      : null;
            const htmlForSpelling =
                typeof document !== 'undefined' ? getLiveBlockBodyHtml(block.id) || block.content : block.content;
            const agentSpell =
                spellObj && typeof spellObj === 'object' && !spellObj.FOUT
                    ? feedbackToSuggestions(
                          spellObj,
                          block.id,
                          block.chapterId,
                          'agent_spelling_grammatica',
                          plain,
                          'spelling',
                          htmlForSpelling
                      )
                    : [];
            list.push(
                ...mergeSpellingSuggestionsWithLocalSpaceRules(
                    htmlForSpelling,
                    block.id,
                    block.chapterId,
                    agentSpell
                )
            );
            if (list.length > 0) {
                const visible = list.filter(s => !dismissedSuggestionIds.has(s.id));
                if (visible.length > 0) next[block.id] = visible;
            }
        }
        lastSuggestions = next;
    }

