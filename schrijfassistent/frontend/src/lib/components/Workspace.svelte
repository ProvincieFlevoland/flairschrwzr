    /**
     * Reads current body HTML from the live editor DOM (fallback: empty).
     * @param {string} blockId
     */
    function getLiveBlockBodyHtml(blockId) {
        if (typeof document === 'undefined') return '';
        const safe =
            typeof CSS !== 'undefined' && typeof CSS.escape === 'function'
                ? CSS.escape(blockId)
                : String(blockId).replace(/\\/g, '\\\\').replace(/"/g, '\\"');
        const el = root().querySelector(`[data-block-id="${safe}"] .cell-content`);
        return el?.innerHTML ?? '';
    }

    /**
     * Schedules (or clears) the automatic structure+B1+spelling chain after {@link AUTO_AI_DELAY_MS}.
     * @param {string} blockId
     * @param {string|null|undefined} chapterId
     * @param {string} snapshotHtml — HTML at schedule time; used when the timeout fires.
     */
    function scheduleAutoAiAnalysisChain(blockId, chapterId, snapshotHtml) {
        if (workspaceDisposed || !get(uiSettings).autoAi || !chapterId || !isWorkflowAiEnabled(blockWorkflowMap, blockId)) {
            clearTimeout(aiTimers[blockId]);
            delete aiTimers[blockId];
            if (aiAgentPendingUntil[blockId] != null) {
                const cleared = { ...aiAgentPendingUntil };
                delete cleared[blockId];
                aiAgentPendingUntil = cleared;
            }
            return;
        }
        clearTimeout(aiTimers[blockId]);
        const until = Date.now() + AUTO_AI_DELAY_MS;
        aiAgentPendingUntil = { ...aiAgentPendingUntil, [blockId]: until };
        const cid = chapterId;
        const bid = blockId;
        const snap = snapshotHtml;
        aiTimers[blockId] = setTimeout(() => {
            (async () => {
                delete aiTimers[bid];
                const next = { ...aiAgentPendingUntil };
                delete next[bid];
                aiAgentPendingUntil = next;
                const wf = getBlockWorkflowMapLive();
                if (!isWorkflowAiEnabled(wf, bid)) return;
                await Promise.all([
                    triggerAiAnalysis(bid, cid, snap, 'agent_structuur'),
                    triggerAiAnalysis(bid, cid, snap, 'agent_b1')
                ]);
                await triggerAiAnalysis(bid, cid, snap, 'agent_spelling_grammatica');
            })().catch((e) => console.error('Automatic structure/B1/spelling chain failed', e));
        }, AUTO_AI_DELAY_MS);
    }

    /** Immediately runs all AI agents for a block (no timer delay). Used by the in-editor AI button. */
    async function triggerAllAgentsNow(blockId) {
        if (!isWorkflowAiEnabled(blockWorkflowMap, blockId)) return;
        const b = editorBlocks.find((x) => x.id === blockId);
        if (!b?.chapterId) return;
        const snap = getLiveBlockBodyHtml(blockId) || b.content || '';
        // Cancel any pending timer so we don't double-fire
        clearTimeout(aiTimers[blockId]);
        delete aiTimers[blockId];
        const next = { ...aiAgentPendingUntil };
        delete next[blockId];
        aiAgentPendingUntil = next;
        await Promise.all([
            triggerAiAnalysis(blockId, b.chapterId, snap, 'agent_structuur'),
            triggerAiAnalysis(blockId, b.chapterId, snap, 'agent_b1'),
        ]);
        await triggerAiAnalysis(blockId, b.chapterId, snap, 'agent_spelling_grammatica');
    }

    /**
     * Restarts only if an auto-AI countdown is already pending for this block (as when typing continues).
     * Clicking in the block without new input avoids clearing a timer that has not started yet.
     * @param {string} blockId
     */
    function bumpAutoAiDelayForBlock(blockId) {
        if (currentUser.role !== 'auteur') return;
        const b = editorBlocks.find((x) => x.id === blockId);
        if (!b?.chapterId || !isWorkflowAiEnabled(blockWorkflowMap, blockId)) return;
        const hasPending = aiTimers[blockId] != null || aiAgentPendingUntil[blockId] != null;
        if (!hasPending) return;
        const html = getLiveBlockBodyHtml(blockId) || b.content || '';
        scheduleAutoAiAnalysisChain(blockId, b.chapterId, html);
    }

    /**
     * Persists changes from one block to `content` + db; optionally schedules auto-AI.
     * @param {string} blockId
     * @param {string} newBodyHtml
     * @param {string|null} [newHeaderHtml]
     */
    // Known behaviour: `parseContentToBlocks` keeps the "\n" text nodes inside each block and the join below adds "\n" after each header and
    // between blocks, so every edit grows the inter-block newlines; an emptied block keeps the `<br>` Chrome leaves.
    function updateBlockContent(blockId, newBodyHtml, newHeaderHtml = null) {
        if (isBlockWorkflowDone(blockId)) return;
        const db = get(dbStore);
        const notaIndex = db.notas.findIndex(n => n.id === notaId);
        if (notaIndex > -1) {
            const blocks = parseContentToBlocks(db.notas[notaIndex].content);
            const targetBlock = blocks.find(b => b.id === blockId);
            const chapterId = targetBlock?.chapterId;

            const updatedBlocks = blocks.map(b => {
                if (b.id !== blockId) return b;
                const next = { ...b, content: newBodyHtml };
                if (newHeaderHtml != null && String(newHeaderHtml).trim()) {
                    next.headerHtml = newHeaderHtml;
                }
                return next;
            });

            const newFullContent = updatedBlocks.map(b => {
                if (b.chapterId) {
                    return `${b.headerHtml}\n${b.content}`;
                }
                return b.content;
            }).join('\n');

            db.notas[notaIndex].content = newFullContent;
            db.notas[notaIndex].lastModified = new Date().toISOString();
            if (currentUser.role === 'auteur' && !db.notas[notaIndex].authors.includes(currentUser.name)) {
                db.notas[notaIndex].authors.push(currentUser.name);
            }
            dbStore.set({ ...db });
            saveDB();
            triggerAutosaveDebounce(); // Start autosave timer after edit

            // Keep `content` / `nota` in sync immediately so BlockEditor never resets the DOM from stale
            // `block.content` (e.g. after accepting a suggestion while focus is in the modal).
            const fresh = get(dbStore).notas[notaIndex];
            content = newFullContent;
            nota = { ...fresh };

            // Taalreview-feedback (`chapterFeedbacksSpelling`) bewust niet wissen bij elke wijziging:
            // anders verdwijnen alle open suggesties na één “Accepteren”. Verversen gaat via nieuwe AI-run.

            if (skipNextAutoAi) {
                skipNextAutoAi = false;
            } else {
                scheduleAutoAiAnalysisChain(blockId, chapterId, newBodyHtml);
            }
            scheduleAutoTitleGeneration(newFullContent);
        }
    }

