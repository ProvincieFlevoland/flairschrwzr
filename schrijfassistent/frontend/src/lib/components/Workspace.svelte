    function peekNextInFilteredQueue(blockId, suggestionId) {
        const q = getFilteredSuggestionQueue();
        const idx = q.findIndex((p) => p.blockId === blockId && p.suggestionId === suggestionId);
        if (idx === -1) return q[0] ?? null;
        return q[idx + 1] ?? null;
