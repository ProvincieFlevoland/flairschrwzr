    /**
     * Removes persisted agent feedback for one chapter (before a targeted re-run).
     * @param {string} chapterId
     * @param {string} blockId
     * @param {Array<'agent_b1'|'agent_spelling_grammatica'|'agent_woordenlijst'|'agent_structuur'>} assignments
     */
    function clearChapterFeedbackForAssignments(chapterId, blockId, assignments) {
        const db = get(dbStore);
        const nIdx = db.notas.findIndex((n) => n.id === notaId);
        if (nIdx === -1) return;
        let changed = false;
        for (const assignment of assignments) {
            const field = feedbackFieldForAssignment(assignment);
            if (db.notas[nIdx][field]?.[chapterId] != null) {
                delete db.notas[nIdx][field][chapterId];
                changed = true;
            }
            clearDismissedMatchingPrefix(dismissPrefixForAssignment(assignment, chapterId, blockId));
        }
        if (changed) {
            dbStore.set({ ...db });
            saveDB();
            nota = { ...db.notas[nIdx] };
        }
    }

    /** Drops accepted-suggestion undo entries whose ids match any of the given prefixes. */
    function clearAcceptedSuggestionsForPrefixes(...prefixes) {
        const next = { ...acceptedSuggestions };
        let changed = false;
        for (const id of Object.keys(next)) {
            if (prefixes.some((p) => id.startsWith(p))) {
                delete next[id];
                changed = true;
            }
        }
        if (changed) acceptedSuggestions = next;
    }

