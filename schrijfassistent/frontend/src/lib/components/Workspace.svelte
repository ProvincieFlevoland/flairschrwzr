    /**
     * Splits nota HTML on `h2.dynamic-chapter` into editor blocks with id/title/content.
     * @param {string|null|undefined} html
     * @returns {Array<{id: string, title: string, content: string, chapterId: string|null, headerHtml?: string}>}
     */
    function parseContentToBlocks(html) {
        if (!html) return [];
        const temp = document.createElement('div');
        // SAFETY: every nota HTML that becomes DOM passes the safety filter here, the one place where
        // `content` is split into blocks (on load, on every edit and for the sidebar); a clean nota is returned unchanged.
        // Cost: the filter parses the whole nota once per call and this function runs on every keystroke.
        setNotaHtml(temp, html.replace(/<p>\s*Start met typen\.\.\.\s*<\/p>/g, ''));
        const blocks = [];
        let currentBlock = { id: 'block-0', title: 'Algemeen', content: '', chapterId: null };
        let blockIndex = 1;

        Array.from(temp.childNodes).forEach(node => {
            if (node.nodeType === 1 && node.tagName === 'H2' && node.classList.contains('dynamic-chapter')) {
                if (currentBlock.content.trim() !== '' || blocks.length > 0 || currentBlock.id !== 'block-0') {
                    blocks.push(currentBlock);
                }
                const chId = node.getAttribute('data-chapter-id');
                currentBlock = {
                    id: chId ? `block-${chId}` : `block-${blockIndex++}`,
                    chapterId: chId,
                    title: node.innerText,
                    headerHtml: node.outerHTML,
                    content: ''
                };
            } else {
                // Taking `node.textContent` of a top-level text node into `content` as it is would turn entity text such as
                // `&lt;b&gt;` back into markup and, in the worst case, into a live `<img onerror>`.
                // The text is escaped here (`escapeHtmlText`), so a stored text node
                // stays text; the re-parse of this string by the editor gives the same text node again.
                currentBlock.content += (node.nodeType === 3 ? escapeHtmlText(node.textContent) : node.outerHTML) || '';
            }
        });
        blocks.push(currentBlock);
        return blocks;
    }

