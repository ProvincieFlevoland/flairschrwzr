    /** Longest error text stored with a nota (a failed call can return a whole HTML error page;). */
    const MAX_STORED_ERROR_CHARS = 2000;
    /** Longest agent answer (as JSON) stored with a nota; real answers are a few kB. */
    const MAX_STORED_AI_JSON_CHARS = 100000;

    /** @param {unknown} text @returns {string} */
    function boundedErrorText(text) {
        const t = typeof text === 'string' ? text : String(text ?? '');
        return t.length > MAX_STORED_ERROR_CHARS ? `${t.slice(0, MAX_STORED_ERROR_CHARS)}…` : t;
    }

    /** An answer that is too large to store becomes an error row instead of filling the cache and the Blob. */
    function boundedAiResponse(feedback) {
        let size = 0;
        try {
            size = JSON.stringify(feedback)?.length ?? 0;
        } catch {
            size = Infinity;
        }
        return size > MAX_STORED_AI_JSON_CHARS ? { FOUT: 'Het AI-antwoord is te groot om te verwerken.' } : feedback;
    }

