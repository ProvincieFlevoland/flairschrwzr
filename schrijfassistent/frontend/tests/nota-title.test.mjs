import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import {
    DEFAULT_NOTA_TITLE,
    MAX_AUTO_TITLE_WORDS,
    isTitleAutoGenEligible,
    hasSubstantiveContentForTitle,
    clampAutoGeneratedTitle
} from '../src/lib/utils/notaTitle.js';

describe('notaTitle', () => {
    it('isTitleAutoGenEligible only for default title without manual flag', () => {
        assert.equal(
            isTitleAutoGenEligible({ title: DEFAULT_NOTA_TITLE, titleManuallySet: false }),
            true
        );
        assert.equal(
            isTitleAutoGenEligible({ title: DEFAULT_NOTA_TITLE, titleManuallySet: true }),
            false
        );
        assert.equal(
            isTitleAutoGenEligible({ title: 'Aangepaste titel', titleManuallySet: false }),
            false
        );
    });

    it('clampAutoGeneratedTitle limits to max words and strips quotes', () => {
        assert.equal(MAX_AUTO_TITLE_WORDS, 5);
        assert.equal(
            clampAutoGeneratedTitle('Verlenging subsidie energietransitie 2026 extra woorden hier'),
            'Verlenging subsidie energietransitie 2026 extra'
        );
        assert.equal(
            clampAutoGeneratedTitle('"Zeer lange GS-nota titel over het beleid."'),
            'Zeer lange GS-nota titel over'
        );
        assert.equal(clampAutoGeneratedTitle('  Eén regel\nTweede regel  '), 'Eén regel');
    });

    it('hasSubstantiveContentForTitle ignores template placeholder text', () => {
        const placeholderHtml =
            '<h2 class="dynamic-chapter" data-chapter-id="c1">Onderwerp</h2>' +
            '<p><i>Schrijf hier een korte, krachtige titel.</i></p>';
        assert.equal(hasSubstantiveContentForTitle(placeholderHtml), false);

        const withText =
            '<h2 class="dynamic-chapter" data-chapter-id="c1">Onderwerp</h2>' +
            '<p>Verlenging subsidie energietransitie 2026</p>';
        assert.equal(hasSubstantiveContentForTitle(withText), true);
    });
});
