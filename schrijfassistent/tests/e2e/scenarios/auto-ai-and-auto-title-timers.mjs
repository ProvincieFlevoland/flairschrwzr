import assert from 'node:assert/strict';
import { scratchNota, fixture } from '../lib/api.mjs';
import { openNota, setSetting, typeInCell, agentCalls, putCalls, waitFor, wordCount } from '../lib/app.mjs';

const TEXT = 'Parkeergarage onder het provinciehuis bouwen voor bezoekers en medewerkers.';

/** Type in block h1 and wait -> agent calls at ~10 s, structuur and Direct Duidelijk in parallel then taalreview; generate-nota-title at ~15 s; title <= 5 words. */
export default {
  id: 'auto-ai-and-auto-title-timers', title: 'auto-AI chain at 10 s, auto-title at 15 s', timeout: 120000,
  async run({ page, adapter, api, rec, mockLog, record, cleanup }) {
    const nota = scratchNota('auto-ai-and-auto-title-timers', { title: 'Nieuwe Concept Nota', titleManuallySet: false });
    await api.putNota(nota);
    cleanup(() => api.deleteNota(nota.id));
    await adapter.enter(page, { name: 'Test Auteur', role: 'auteur' });
    await setSetting(page, 'Auto-AI na typen', true);            // default off (uiStore.js DEFAULT_SETTINGS.autoAi = false)
    await openNota(page, nota.title);
    const logMark = mockLog.mark();
    const tEnd = await typeInCell(page, 'h1', TEXT);
    const since = tEnd - 5000;

    // 1. the three agents for h1
    const agents = await waitFor(() => {
      const c = agentCalls(rec, since).filter((x) => x.chapter === 'h1');
      return c.length >= 3 && c.every((x) => x.doneTs) ? c : null;
    }, { timeout: 25000, what: 'three agent calls for h1' });
    const by = Object.fromEntries(agents.map((a) => [a.assignment, a]));
    record('agent_offsets_ms', Object.fromEntries(agents.map((a) => [a.assignment, a.ts - tEnd])));
    assert.deepEqual(Object.keys(by).sort(), ['agent_b1', 'agent_spelling_grammatica', 'agent_structuur']);
    for (const k of ['agent_structuur', 'agent_b1']) {
      const dt = by[k].ts - tEnd;
      assert.ok(dt >= 9000 && dt <= 12500, `${k} fired ${dt} ms after the last keystroke; expected ~10 s (AUTO_AI_DELAY_MS)`);
    }
    assert.ok(Math.abs(by.agent_structuur.ts - by.agent_b1.ts) < 1500, 'structuur and Direct Duidelijk start together (Promise.all)');
    const bothDone = Math.max(by.agent_structuur.doneTs, by.agent_b1.doneTs);
    assert.ok(by.agent_spelling_grammatica.ts >= bothDone - 20, `taalreview (${by.agent_spelling_grammatica.ts}) starts after structuur and B1 finished (${bothDone})`);
    assert.equal(by.agent_structuur.userMessage, TEXT, 'user_message is the typed text (stripBlockPlain)');
    for (const a of agents) assert.equal(a.userMessage, TEXT, `${a.assignment}: user_message travels in the POST body`);
    assert.equal(agents.filter((a) => a.ts < tEnd + 8500).length, 0, 'no agent call before the delay elapsed');

    // 2. the title at ~15 s, clamped to 5 words
    const title = await waitFor(() => { const t = rec.api('POST', /generate-nota-title/, since); return t.length && t[0].doneTs ? t : null; }, { timeout: 25000, what: 'generate-nota-title' });
    const dtTitle = title[0].ts - tEnd;
    record('title_offset_ms', dtTitle);
    assert.equal(title.length, 1);
    assert.ok(dtTitle >= 14000 && dtTitle <= 17500, `title generated ${dtTitle} ms after the last keystroke; expected ~15 s (AUTO_TITLE_DELAY_MS)`);
    const chapters = JSON.parse(title[0].postData).chapters;
    assert.equal(chapters[0].title, 'Onderwerp'); assert.equal(chapters[0].content, TEXT);
    const fx = fixture('ai/title.json');
    await waitFor(async () => (await page.locator('button[title="Klik om de titel te bewerken"]').textContent()).includes('Parkeergarage'), { what: 'title applied in the editor' });
    const shown = (await page.locator('button[title="Klik om de titel te bewerken"]').textContent()).trim();
    record('title_shown', shown);
    assert.ok(wordCount(shown) <= 5, `title has at most 5 words: ${shown}`);
    assert.equal(shown, fx.expected, 'title equals the backend-clamped fixture, unchanged by clampAutoGeneratedTitle');

    // 3. server-side order in the mock's call log (when readable here)
    if (mockLog.available) {
      const calls = mockLog.since(logMark).map((c) => c.assignment);
      record('mock_log_order', calls);
      assert.deepEqual(calls.slice(0, 2).sort(), ['agent_b1', 'agent_structuur']);
      assert.deepEqual(calls.slice(2), ['agent_spelling_grammatica', 'title']);
    }
    // 4. autosave debounce: one PUT about 10 s after the last edit
    const puts = putCalls(rec, nota.id, since);
    record('put_offsets_ms', puts.map((p) => p.ts - tEnd));
    assert.ok(puts.some((p) => p.ts - tEnd >= 9000 && p.ts - tEnd <= 12500), 'debounced autosave PUT at ~10 s');
  },
};
