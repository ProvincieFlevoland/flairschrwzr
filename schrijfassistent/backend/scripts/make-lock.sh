#!/usr/bin/env bash
# Generates requirements.lock (pinned, hashed) from requirements.txt. Needs PyPI access, so it runs
# on a developer machine or in CI, not offline. Commit the result; the Dockerfile then
# installs it with --require-hashes. Python 3.12 matches the image.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."
uv pip compile --generate-hashes --python-version 3.12 --no-header requirements.txt -o requirements.lock.new
{
  echo "# Hashed lock for the python:3.12-slim image. Generated by scripts/make-lock.sh from requirements.txt."
  cat requirements.lock.new
} > requirements.lock
rm requirements.lock.new
echo "requirements.lock written: $(grep -c -- '--hash=' requirements.lock) hashes"
